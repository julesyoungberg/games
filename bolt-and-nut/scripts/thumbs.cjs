// Renders a small preview picture of every level (fancy look) into src/thumbs.js.
// Run after changing levels or the renderer: node build.mjs && node scripts/thumbs.cjs && node build.mjs
const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const p = await b.newPage({ viewport: { width: 800, height: 500 } });
  await p.goto('file://' + process.cwd() + '/dist/index.html');
  await p.waitForTimeout(1000);
  await p.evaluate(() => { __bn.view.setQuality('high'); __bn.view.quality = 'fixed'; });
  const n = await p.evaluate(() => __bn.count);
  const out = {};
  for (let i = 0; i < n; i++) {
    await p.evaluate(i => __bn.start(i), i);
    await p.waitForTimeout(1500);
    out[i] = await p.evaluate(() => {
      const v = __bn.view, w = __bn.world;
      for (let k = 0; k < 3; k++) v.draw(w, 1 / 60, { snap: true, zoom: 1.45 });
      const c = document.createElement('canvas'); c.width = 320; c.height = 200;
      c.getContext('2d').drawImage(v.renderer.domElement, 0, 0, 320, 200);
      return c.toDataURL('image/jpeg', 0.72);
    });
    process.stdout.write(i + ' ');
  }
  fs.writeFileSync('src/thumbs.js', '// generated by scripts/thumbs.cjs\nexport default ' + JSON.stringify(out) + ';\n');
  console.log('\nsrc/thumbs.js', (fs.statSync('src/thumbs.js').size / 1024).toFixed(0), 'KB');
  await b.close();
})();
